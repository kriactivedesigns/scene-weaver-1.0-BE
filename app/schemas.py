import uuid
from pydantic import BaseModel
from datetime import datetime
from typing import Optional

# This is a base model that contains fields common to both creation and response.
class ProjectBase(BaseModel):
    projectName: str
    description: Optional[str] = None
    aspectRatio: Optional[str] = "16:9"
    visualStyle: Optional[str] = "Dynamic Line Art (Gesture Drawing)"

# This model is used specifically when creating a new project
class ProjectCreate(ProjectBase):
    pass

# This model is used specifically when updating a project
class ProjectUpdate(ProjectBase):
    pass

# This model is used when returning a project from the API
# It includes fields that are generated by the database, like id and timestamps.
class Project(ProjectBase):
    id: uuid.UUID
    createdAt: datetime
    updatedAt: datetime

    class Config:
        # This allows Pydantic to create the schema from an ORM model
        from_attributes = True

# World Schemas
class WorldBase(BaseModel):
    name: str
    description: Optional[str] = None
    imagePath: Optional[str] = None

class WorldCreate(WorldBase):
    pass

class WorldUpdate(WorldBase):
    name: Optional[str] = None
    description: Optional[str] = None
    imagePath: Optional[str] = None
    pass

class WorldDelete(WorldBase):
    pass

class World(WorldBase):
    id: uuid.UUID
    projectId: uuid.UUID
    createdAt: datetime
    updatedAt: datetime

    class Config:
        from_attributes = True

